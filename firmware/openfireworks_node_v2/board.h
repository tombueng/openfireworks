// ---------------------------------------------------------------------------------------------
// Shift chain: MOSI -> U1 -> U2 -> U3 -> U4 -> QH' -> SR_RB.  32-bit word, bit n:
//   bits 0..7   U1 QA..QH : SEL_A, SEL_B, SEL_C (level-1 mux U5/U6/U7), SELH_A..C (level-2 mux U8),
//                           QG = marker (always 1 in IDLE, so a readback stuck at 0 is seen), QH spare
//   bits 8..15  U2 QA..QH : SRGATE0..7
//   bits 16..23 U3 QA..QH : SRGATE8..15
//   bits 24..31 U4 QA..QH : SRGATE16..23
// The word is shifted MSB first (bit 31 ends in U4 QH). Gate n = channel n = jack J(n+1).
// ---------------------------------------------------------------------------------------------
#define NCH 24
static const uint32_t W_MARKER    = 1u << 6;
static const uint32_t W_GATE_MASK = 0xFFFFFF00u;
static inline uint32_t w_gate(int ch) { return 1u << (8 + ch); }
static inline uint32_t w_mux(int lo, int hi) { return (uint32_t)(lo & 7) | ((uint32_t)(hi & 7) << 3); }
// U8 X3 is unconnected: the "park" code leaves MUX_ADC on its 100k pull-up only (reads saturated).
static const int MUX_PARK = -1;
static inline uint32_t w_mux_for(int ch) { return ch < 0 ? w_mux(0, 3) : w_mux(ch % 8, ch / 8); }
static inline uint32_t w_idle(int mux_ch) { return w_mux_for(mux_ch) | W_MARKER; }

